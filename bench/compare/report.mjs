#!/usr/bin/env node
// Turns bench/results/compare-*.json into docs/benchmarks-compare.md and docs/benchmarks/compare.svg.
//
//   node bench/compare/report.mjs [--labels cloud-node22,cloud-bun1] [file.json ...]
//
// With no files, every non-quick compare result is used, grouped by label; several runs of one
// label are merged by taking the median of the per-run medians.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geomean, median } from '../lib/stats.mjs';
import { ALGORITHMS, LIBRARIES } from './libs.mjs';

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args.splice(i, 2)[1] : null;
};
const onlyLabels = opt('labels')?.split(',');
const files = args.filter((a) => a.endsWith('.json'));
const resultsDir = join(REPO, 'bench', 'results');
const all = (files.length ? files : readdirSync(resultsDir).filter((f) => f.startsWith('compare-') && f.endsWith('.json')).map((f) => join(resultsDir, f)))
  .map((f) => JSON.parse(readFileSync(f, 'utf8')))
  .filter((r) => r.kind === 'compare' && (files.length || r.mode !== 'quick'))
  .filter((r) => !onlyLabels || onlyLabels.includes(r.label));
if (!all.length) throw new Error('no compare results; run node bench/compare/run.mjs first');

const RT_ORDER = { node: 0, bun: 1, deno: 2 };
const groups = new Map();
for (const r of all) {
  if (!groups.has(r.label)) groups.set(r.label, []);
  groups.get(r.label).push(r);
}
const runs = [...groups.entries()].map(([label, rs]) => ({ label, runs: rs, ...merge(rs) }))
  .sort((a, b) => (RT_ORDER[a.env.runtime] - RT_ORDER[b.env.runtime]) || a.label.localeCompare(b.label));

function merge(rs) {
  const cells = new Map();
  for (const r of rs) {
    for (const row of r.rows) {
      const k = `${row.algorithm}|${row.size}`;
      if (!cells.has(k)) cells.set(k, []);
      cells.get(k).push(row);
    }
  }
  const rows = [...cells.values()].map((list) => {
    const results = {};
    for (const name of new Set(list.flatMap((x) => Object.keys(x.results)))) {
      const ms = list.map((x) => x.results[name]?.median_ms).filter((v) => v > 0);
      if (ms.length) results[name] = { median_ms: median(ms), runs: ms.length };
    }
    const dropped = Object.assign({}, ...list.map((x) => x.dropped ?? {}));
    return { algorithm: list[0].algorithm, size: list[0].size, results, dropped };
  });
  const latest = rs.reduce((a, b) => (a.date >= b.date ? a : b));
  return { rows, env: latest.environment, libraries: latest.libraries, sizes: latest.input_sizes, date: latest.date };
}

const NG = 'crypto-api-ng';
const libMeta = new Map(LIBRARIES.map((l) => [l.name, l]));
const competitors = LIBRARIES.filter((l) => !l.subject && !l.informational).map((l) => l.name);
const shortOf = (n) => libMeta.get(n)?.short ?? n;
const rtName = (env) => ({ node: 'Node', bun: 'Bun', deno: 'Deno' }[env.runtime] + ' ' + env.runtime_version);

/** Speed of `name` relative to crypto-api-ng (>1: `name` is faster) for one row. */
const rel = (row, name) => (row.results[name] && row.results[NG] ? row.results[NG].median_ms / row.results[name].median_ms : null);

function summaryOf(run, name, filter = () => true) {
  const xs = run.rows.filter(filter).map((r) => rel(r, name)).filter((v) => v != null);
  return xs.length ? { g: geomean(xs), n: xs.length, min: Math.min(...xs), max: Math.max(...xs) } : null;
}

const x2 = (v) => (v >= 10 ? v.toFixed(0) : v >= 1 ? v.toFixed(1) : v.toFixed(2)) + '×';
const sizeName = (s) => (s >= 1048576 ? `${s / 1048576} MiB` : s >= 1024 ? `${s / 1024} KiB` : `${s} B`);
const fmtCell = (row, name) => {
  const r = row.results[name];
  if (!r) return '';
  if (row.size >= 65536) {
    const mb = row.size / 1e6 / (r.median_ms / 1000);
    return mb >= 100 ? mb.toFixed(0) : mb.toFixed(1);
  }
  const k = 1 / r.median_ms; // thousands of hashes per second
  return k >= 100 ? k.toFixed(0) : k.toFixed(1);
};
const table = (head, body, align = []) => [
  `| ${head.join(' | ')} |`,
  `|${head.map((_, i) => (align[i] === 'l' ? ' --- ' : ' ---: ')).join('|')}|`,
  ...body.map((r) => `| ${r.join(' | ')} |`),
].join('\n');

const out = [];
const p = (...l) => out.push(...l, '');

p('# crypto-api-ng compared with other hash libraries');
p('Generated by `node bench/compare/report.mjs` from `bench/results/compare-*.json`. Do not edit by hand; rerun the benchmark (see [Reproduce](#reproduce)). For crypto-api-ng against the original crypto-api 0.8.5, see [benchmarks.md](benchmarks.md).');
p('Each cell hashes one `Uint8Array` in one call, the way a user of that library would write it (see [What is called](#what-is-called)). Every library\'s digest is checked against the others before it is timed.');

p('## Summary');
p('Speed of each library relative to crypto-api-ng, as the geometric mean over every algorithm and input size both support. Above 1× the other library is faster; below 1× crypto-api-ng is faster. The range is the slowest and fastest single cell.');
const sumHead = ['Library', ...runs.map((r) => rtName(r.env))];
const sumBody = competitors.map((name) => [
  shortOf(name),
  ...runs.map((run) => {
    const s = summaryOf(run, name);
    return s ? `${x2(s.g)} (${x2(s.min)} to ${x2(s.max)}, ${s.n} cell${s.n > 1 ? 's' : ''})` : 'not run';
  }),
]);
p(table(sumHead, sumBody, ['l']));
p('![Speed of other hash libraries relative to crypto-api-ng](benchmarks/compare.svg)');

// Short-input view: the per-call cost dominates there and the picture is different.
const small = Math.min(...runs[0].sizes);
const large = Math.max(...runs[0].sizes);
if (small !== large) {
p(`At ${sizeName(small)} and at ${sizeName(large)} separately:`);
p(table(['Library', ...runs.flatMap((r) => [`${rtName(r.env)}, ${sizeName(small)}`, `${sizeName(large)}`])],
  competitors.map((name) => [shortOf(name), ...runs.flatMap((run) => [small, large].map((sz) => {
    const s = summaryOf(run, name, (r) => r.size === sz);
    return s ? x2(s.g) : '';
  }))]), ['l']));
}

p('## Reading the results');
p(
  '- **crypto-api-ng is not the fastest option for hashing bytes.** hash-wasm (WebAssembly) is faster in every cell, by about 4× overall. node:crypto (native code) is faster everywhere except a few 32 B cells, mostly under Deno, where its per-call cost is higher. crypto-api-ng is faster than crypto-js and hash.js in nearly every cell; the exceptions are 32 B inputs under Bun.',
  '- **Against the pure JavaScript libraries it depends on the algorithm.** crypto-api-ng is 2 to 3 times faster than `@noble/hashes` and `js-sha3` for SHA3-256 and Keccak-256, and faster than `@noble/hashes` for BLAKE2b and (on Node and Deno) BLAKE3, and than `js-sha512` for SHA-512. `@noble/hashes` is about 2 times faster for SHA-1 and SHA-256, and `js-sha256` is about 10 times faster for SHA-256 at 64 KiB and up, because it runs near 800 MB/s where crypto-api-ng stays near 90 MB/s. `js-md5` is 2 to 3 times faster for MD5.',
  '- **Most of the gap is in the JavaScript layer, not the WebAssembly.** Version 1 keeps the 0.8.5 hasher design: `update()` turns bytes into a binary string, appends it to `state.message` (so `getState()` keeps the 0.8.5 format) and copies it into WebAssembly memory one character at a time. That caps it near 100 MB/s on this machine whatever the algorithm, which is why CRC-32 and xxHash64 are no faster than SHA-256. The `ng core` row calls the same WebAssembly modules directly with a `Uint8Array` (the `raw` contender of [benchmarks.md](benchmarks.md); not a public API) and is about 1.4 to 5.8 times faster, with the same digests. A bytes path that skips the string is the main thing to do before speed can be a selling point.',
  '- **The shipped modules are built for size.** They use `--release=small`; hash-wasm is C compiled for speed. [benchmarks.md](benchmarks.md) has the byte sizes of both builds.',
  '- **What crypto-api-ng offers instead** is the 0.8.5 API and digests, the same code in Node, Bun, Deno and browsers with a pure JavaScript fallback, and algorithms most libraries do not have (HAS-160, MD2, Snefru, RIPEMD-128/256/320, SHA-0, Tiger, Streebog, Whirlpool-0/T).',
  '- **node:crypto is a reference, not a portable choice.** It is OpenSSL (Node) or BoringSSL (Bun) or Rust (Deno) and does not exist in browsers. Which algorithms it has depends on the runtime build, so its cell count differs per runtime.',
  '- **hash-wasm is timed with one hasher created up front** and reset with `init()` per call. Its one-shot helpers (`sha256(data)`) return promises and are slower per call; this is the fastest way to use it.',
  '- **crypto-js needs a WordArray**, so its time includes `WordArray.create(bytes)`. `CryptoJS.SHA3` is Keccak with the original padding, so it is compared under Keccak-256, not SHA3-256.',
  '- **Small inputs measure call overhead.** At 32 B the work is a single block, and the time is mostly object creation and the JavaScript to WebAssembly boundary. crypto-api-ng creates a hasher object and an options copy per call.',
  '- **These are single runs on a shared machine** unless the environment line says otherwise. Run-to-run spread on the cloud sandbox was 3% per cell at the median and up to about 30% at worst in earlier runs (see [benchmarks.md](benchmarks.md)), so read ratios, not absolute numbers, and treat differences under 1.3× as noise.',
);

p('## What is called');
p(table(['Library', 'Kind', 'Version', 'Call timed'], [
  [NG, 'WebAssembly, JavaScript fallback', runs[0].libraries.find((l) => l.name === NG)?.version ?? '', '`const h = new Sha256(); h.update(bytes); h.digest()`'],
  ['ng core (not public)', 'WebAssembly', 'same', 'the WebAssembly exports `init`, `update`, `final` with the input copied into module memory'],
  ['node:crypto', 'native', 'runtime', '`createHash(name).update(bytes).digest()`'],
  ['hash-wasm', 'WebAssembly', ver('hash-wasm'), '`h.init(); h.update(bytes); h.digest("binary")` on a hasher from `await createSHA256()`'],
  ['@noble/hashes', 'JavaScript', ver('@noble/hashes'), '`sha256(bytes)`'],
  ['js-sha*', 'JavaScript', ver('js-sha*'), '`sha256.arrayBuffer(bytes)` (js-sha256, js-sha512, js-sha3, js-sha1, js-md5)'],
  ['hash.js', 'JavaScript', ver('hash.js'), '`hash.sha256().update(bytes).digest()`'],
  ['crypto-js', 'JavaScript', ver('crypto-js'), '`CryptoJS.SHA256(CryptoJS.lib.WordArray.create(bytes))`'],
  ['xxhash-wasm', 'WebAssembly', ver('xxhash-wasm'), '`h64Raw(bytes)` on the instance from `await xxhash()`'],
], ['l', 'l', 'l', 'l']));
function ver(short) {
  const l = runs[0].libraries.find((x) => (x.short ?? x.name) === short);
  return l?.version ?? '';
}
p('WebCrypto (`crypto.subtle.digest`) is left out: it is asynchronous, so a call costs a promise and a microtask, and it only has SHA-1 and SHA-2.');
p('Timing is the harness of [benchmarks.md](benchmarks.md) (`bench/lib/stats.mjs`): warm-up, iteration count calibrated to about 25 ms per sample, 15 samples per library taken in round-robin order so drift hits every library alike, median reported. Input bytes are the same pseudo-random sequence in every run.');

p('## Results');
p('Throughput in MB/s (10^6 bytes per second) for inputs of 64 KiB and up, thousands of hashes per second below that. Higher is faster. An empty cell means the library does not have the algorithm.');
for (const run of runs) {
  const e = run.env;
  p(`### ${rtName(e)} (${run.label})`);
  p(`${e.cpu}, ${e.cpu_count} threads, ${e.platform}; commit ${e.commit ?? 'unknown'}, ${run.date}, ${run.runs.length} run${run.runs.length > 1 ? 's' : ''}.${e.note ? ` ${e.note}` : ''}`);
  const names = [NG, ...LIBRARIES.filter((l) => !l.subject).map((l) => l.name)]
    .filter((n) => run.rows.some((r) => r.results[n]));
  for (const size of run.sizes) {
    const rows = ALGORITHMS.map((a) => run.rows.find((r) => r.algorithm === a.id && r.size === size)).filter(Boolean);
    if (!rows.length) continue;
    p(`**${sizeName(size)}** (${size >= 65536 ? 'MB/s' : 'thousand hashes/s'})`);
    p(table(['Algorithm', ...names.map(shortOf)],
      rows.map((r) => [ALGORITHMS.find((a) => a.id === r.algorithm).label, ...names.map((n) => fmtCell(r, n))]), ['l']));
  }
  const dropped = run.rows.flatMap((r) => Object.keys(r.dropped).map((n) => `${n} (${r.algorithm}, ${sizeName(r.size)})`));
  if (dropped.length) p(`Not timed because the digest differed from the others: ${[...new Set(dropped)].join(', ')}.`);
}

p('## Reproduce');
p('```sh\nscripts/fetch-upstream.sh\nscripts/install-zig.sh && export PATH="$HOME/.local/bin:$PATH"\nzig build js --release=small\nnpm ci --prefix bench/compare --ignore-scripts\nnode bench/compare/run-all.mjs --machine mypc   # node, bun and deno, whichever are installed\nnode bench/compare/report.mjs\n```');
p('`run.mjs` takes `--quick`, `--algorithms md5,sha256`, `--sizes 32,1024`, `--label` and `--note`. See `bench/compare/README.md`.');

const md = out.join('\n').replace(/\n{3,}/g, '\n\n');
writeFileSync(join(REPO, 'docs', 'benchmarks-compare.md'), md);
mkdirSync(join(REPO, 'docs', 'benchmarks'), { recursive: true });
writeFileSync(join(REPO, 'docs', 'benchmarks', 'compare.svg'), chart());
console.error('wrote docs/benchmarks-compare.md and docs/benchmarks/compare.svg');

// Diverging bars on a log scale around 1× (crypto-api-ng), one bar per runtime per library.
function chart() {
  const W = 760, LEFT = 118, RIGHT = 28, TOP = 72, BAR = 7, GAP = 2;
  const series = runs.slice(0, 3);
  const ROW = series.length * (BAR + GAP) + 10;
  const rows = competitors.filter((n) => series.some((run) => summaryOf(run, n)));
  const lo = Math.log10(0.05), hi = Math.log10(100);
  const plotW = W - LEFT - RIGHT;
  const sx = (v) => LEFT + ((Math.log10(Math.min(Math.max(v, 0.05), 100)) - lo) / (hi - lo)) * plotW;
  const H = TOP + rows.length * ROW + 44;
  const ticks = [0.05, 0.1, 0.2, 0.5, 1, 2, 5, 10, 20, 50, 100];
  const grid = ticks.map((v) => `<line class="grid" x1="${sx(v)}" x2="${sx(v)}" y1="${TOP - 8}" y2="${TOP + rows.length * ROW}"/><text class="muted" x="${sx(v)}" y="${TOP + rows.length * ROW + 16}" text-anchor="middle">${v}×</text>`).join('');
  const bar = (v, y, cls, title) => {
    if (v == null) return '';
    const x0 = sx(1), x1 = sx(v);
    const w = Math.max(Math.abs(x1 - x0), 1);
    const r = Math.min(3, w, BAR / 2);
    const d = x1 >= x0
      ? `M${x0} ${y} h${w - r} a${r} ${r} 0 0 1 ${r} ${r} v${BAR - 2 * r} a${r} ${r} 0 0 1 -${r} ${r} h-${w - r} z`
      : `M${x0} ${y} h-${w - r} a${r} ${r} 0 0 0 -${r} ${r} v${BAR - 2 * r} a${r} ${r} 0 0 0 ${r} ${r} h${w - r} z`;
    return `<path class="${cls}" d="${d}"><title>${title}: ${x2(v)}</title></path>`;
  };
  const body = rows.map((n, i) => {
    const y0 = TOP + i * ROW;
    return `<text class="label" x="${LEFT - 10}" y="${y0 + ROW / 2}" text-anchor="end" dominant-baseline="middle">${shortOf(n)}</text>`
      + series.map((run, j) => bar(summaryOf(run, n)?.g, y0 + 4 + j * (BAR + GAP), `s${j}`, `${shortOf(n)}, ${rtName(run.env)}`)).join('');
  }).join('');
  const legend = series.map((run, j) => `<rect class="s${j}" x="${W - 330 + j * 110}" y="16" width="10" height="10" rx="2"/><text class="label" x="${W - 314 + j * 110}" y="25">${rtName(run.env)}</text>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" role="img" aria-label="Speed of other hash libraries relative to crypto-api-ng, geometric mean per runtime">
<style>
svg{--bg:#fcfcfb;--ink:#0b0b0b;--muted:#52514e;--grid:#e6e5e1;--s0:#2a78d6;--s1:#eb6834;--s2:#1baf7a;font-family:system-ui,-apple-system,Segoe UI,sans-serif;font-size:12px}
@media (prefers-color-scheme:dark){svg{--bg:#1a1a19;--ink:#f0efec;--muted:#c3c2b7;--grid:#34332f;--s0:#3987e5;--s1:#d95926;--s2:#199e70}}
.bg{fill:var(--bg)}.label{fill:var(--ink)}.muted{fill:var(--muted)}.grid{stroke:var(--grid);stroke-width:1}.base{stroke:var(--muted);stroke-width:1.5}
.s0{fill:var(--s0)}.s1{fill:var(--s1)}.s2{fill:var(--s2)}.title{font-size:15px;font-weight:600;fill:var(--ink)}
</style>
<rect class="bg" width="${W}" height="${H}"/>
<text class="title" x="12" y="24">Speed relative to crypto-api-ng (right of 1× is faster)</text>
<text class="muted" x="12" y="42">Geometric mean over algorithms and input sizes, one Uint8Array per call; log scale</text>
${legend}
${grid}
<line class="base" x1="${sx(1)}" x2="${sx(1)}" y1="${TOP - 8}" y2="${TOP + rows.length * ROW}"/>
<text class="muted" x="${sx(1) + 6}" y="${TOP + rows.length * ROW + 32}">1× = crypto-api-ng</text>
${body}
</svg>
`;
}
