#!/usr/bin/env node
// Writes src/hash/snefru_rand.zig: the RAND-table digits that crypto-api 0.8.5's
// snefru.mjs turns into its 16 S-boxes at load time. The table is copied
// textually from the vendored original (packages/crypto-api/legacy/hasher/snefru.mjs),
// so the Zig comptime generator in src/hash/snefru.zig starts from the same data.
//
//   node scripts/gen-snefru-rand.mjs           write src/hash/snefru_rand.zig
//   node scripts/gen-snefru-rand.mjs --check   exit 1 if the file is not up to date
//   node scripts/gen-snefru-rand.mjs --dump    also print S-box check values for the Zig tests
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(root, 'packages/crypto-api/legacy/hasher/snefru.mjs'), 'utf8');
const out = join(root, 'src/hash/snefru_rand.zig');

const m = /const randTable = \[([^\]]*)\];/.exec(source);
if (!m) throw new Error('randTable not found in the vendored snefru.mjs');
const digits = m[1].split(',').map((s) => s.trim()).filter(Boolean).map(Number);
if (digits.some((d) => !Number.isInteger(d) || d < 0 || d > 99999)) throw new Error('unexpected table entry');

let text = '//! GENERATED by scripts/gen-snefru-rand.mjs from crypto-api 0.8.5 (snefru.mjs `randTable`). Do not edit.\n' +
  '//!\n' +
  '//! The first part of the random digits from "A Million Random Digits with 100,000 Normal\n' +
  '//! Deviates", RAND Corporation, Free Press, 1955: five decimal digits per entry.\n\n' +
  `pub const table = [${digits.length}]u32{\n`;
for (let i = 0; i < digits.length; i += 10) {
  text += '    ' + digits.slice(i, i + 10).join(', ') + ',\n';
}
text += '};\n';

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('src/hash/snefru_rand.zig is out of date: run node scripts/gen-snefru-rand.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${digits.length} entries)`);
}

if (process.argv.includes('--dump')) {
  // Evaluate the original's module-level S-box generation and print check values.
  const patched = source
    .replace(/^import .*$/gm, '')
    .replace('class Snefru extends Hasher32be', 'class Snefru')
    .replace(/super\([^)]*\);/g, '')
    .replace('export default Snefru;', 'export {SBOX};')
  const mod = await import('data:text/javascript;base64,' + Buffer.from(patched).toString('base64'));
  const { SBOX } = mod;
  let h = 0x811c9dc5;
  for (let i = 0; i < 16; i++) {
    let tableHash = 0x811c9dc5;
    for (let r = 0; r < 256; r++) {
      const v = SBOX[i][r] >>> 0;
      for (const sh of [0, 8, 16, 24]) {
        tableHash = Math.imul(tableHash ^ ((v >>> sh) & 0xff), 0x01000193) >>> 0;
      }
    }
    h = Math.imul(h ^ tableHash, 0x01000193) >>> 0;
    const first = Array.from(SBOX[i].slice(0, 4), (v) => '0x' + (v >>> 0).toString(16).padStart(8, '0')).join(', ');
    const last = '0x' + (SBOX[i][255] >>> 0).toString(16).padStart(8, '0');
    console.log(`sbox ${i}: fnv1a=0x${tableHash.toString(16).padStart(8, '0')} first=[${first}] last=${last}`);
  }
  console.log(`all: fnv1a=0x${h.toString(16).padStart(8, '0')}`);
}
