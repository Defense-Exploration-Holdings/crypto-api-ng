// crypto-api-ng:facade
'use strict';

import LegacySnefru from "../../legacy/hasher/snefru.mjs";
import {wasmBytes} from "../../wasm/snefru.mjs";
import {instantiate, STATE_OFF, OUT_OFF, INPUT_OFF} from "../wasm/family.mjs";

/*
 * Snefru with the compression and padding done in wasm, and everything else
 * left to the original JavaScript. Same design as md5.mjs (recipe in
 * docs/porting-guide.md): the facade extends the verbatim 0.8.5 class and
 * overrides only `process()` and `finalize()`; `this.state` stays the original
 * plain object, and any case the wasm code does not model exactly goes to the
 * original.
 *
 * Snefru specifics:
 *
 *  - The block is `16 - words` words, so its size depends on `options.length`.
 *    wasm serves every digest of 1..15 words in `process()` (the block size is
 *    the instance's `blockSizeInBytes`, which must equal `4 * (16 - words)`),
 *    and 1..14 words in `finalize()` (with 15 words the original cannot finalize:
 *    its padding needs a negative length and throws RangeError, so that is left
 *    to the original too).
 *  - `options.rounds` is read at every block by the original. Integers 1..8 go
 *    to wasm; everything else (0, negative, fractions, 9 and up, which throw
 *    TypeError in the original, strings, ...) is original code.
 *  - The S-boxes are generated by the original module when it loads; wasm has
 *    its own copy built at compile time.
 *  - Divergence 1 of the v1 plan: where the original would loop forever (a
 *    block size of 0 or less, i.e. `options.length >= 512`), `process()`
 *    throws RangeError instead.
 *  - The original's scratch array `this.W` and `blockUnits` are not filled on
 *    the wasm path.
 */

/** Byte offsets inside the Zig `snefru.State` (src/hash/snefru.zig), relative to STATE_OFF. */
const O_WORDS = 60;
const O_ROUNDS = 61;
const O_BUFFERED = 62;
const O_LENGTH = 64;
const O_BUF = 68;
const SIZE = 128;

/** The internals the wasm code replaces. An override of any of them must be honored. */
const P = LegacySnefru.prototype;
const ORIGINAL_BLOCK = P.processBlock;
const ORIGINAL_BITS = P.addLengthBits;
const ORIGINAL_PAD = P.addPaddingZero;
const ORIGINAL_HASH = P.getStateHash;

// The wasm module is compiled on first use, not at import. A failure (no
// WebAssembly, CSP, Workers, ...) is remembered so it is not retried, and every
// call then delegates to the original.
let rt;
let rtTried = false;
let u8;
let i32;
let u32;
let wasmCalls = 0;

function runtime() {
  if (!rtTried) {
    rtTried = true;
    rt = instantiate(wasmBytes, {snefru: SIZE});
    if (rt) {
      u8 = rt.u8;
      i32 = new Int32Array(u8.buffer);
      u32 = new Uint32Array(u8.buffer);
    }
  }
  return rt;
}

/**
 * Test-only hooks; not public API and not kept in later releases.
 */
export const _internal = {
  /** Number of calls that ran in wasm so far. */
  wasmCalls() {
    return wasmCalls;
  },
  /** The instantiated wasm runtime, or null. */
  runtime() {
    return runtime();
  },
  /** Forget the cached runtime; with `disable`, behave as if WebAssembly failed. */
  reset(disable) {
    rtTried = !!disable;
    rt = null;
  }
};

/** The `rounds` value wasm can run (an integer 1..8), or -1. */
function roundsOf(options) {
  if (options === null || typeof options !== 'object') return -1;
  const r = options.rounds;
  return Number.isInteger(r) && r >= 1 && r <= 8 ? r : -1;
}

/**
 * True when `hash` holds `1..max` JS numbers. The original only xors them
 * (`x | 0`, `x ^ y`), which is ToInt32 for every number, the same conversion
 * an Int32Array store performs, so any number is exact.
 */
function wordsOk(hash, max) {
  if (!Array.isArray(hash)) return false;
  const n = hash.length;
  if (n < 1 || n > max) return false;
  for (let i = 0; i < n; i++) {
    if (typeof hash[i] !== 'number') return false;
  }
  return true;
}

/** Copy the new hash words back, the way the original writes them (in place, as int32). */
function store(hash, w, n) {
  for (let k = 0; k < n; k++) hash[k] = i32[w + k];
}

/**
 * Calculates Snefru v2.0 (2 rounds 128, 4 rounds 256), Snefru v2.5 (8 rounds)
 * hash. Same API, output and `getState()` JSON as crypto-api 0.8.5; see
 * legacy/hasher/snefru.mjs for the original documentation and examples.
 */
class Snefru extends LegacySnefru {
  /**
   * @param {Object} [options]
   */
  constructor(options) {
    // Spelled out so `Snefru.length` is 1, as in 0.8.5.
    super(options);
  }

  /**
   * Process ready blocks
   *
   * @protected
   * @ignore
   */
  process() {
    const state = this.state;
    if (state === null || typeof state !== 'object') return super.process();
    const message = state.message;
    const hash = state.hash;
    const options = this.options;
    const size = this.blockSizeInBytes;
    if (typeof message !== 'string' || typeof size !== 'number' || !Array.isArray(hash)) {
      return super.process();
    }

    if (size <= 0) {
      // 0.8.5 loops forever here (block size 0 or negative: `length >= 512`) unless
      // processBlock throws first. Throw instead (a deliberate v1 difference, see the package README).
      if (this.processBlock === ORIGINAL_BLOCK && options !== null && typeof options === 'object' &&
        typeof options.rounds === 'number' && (options.rounds << 1) <= 16) {
        throw new RangeError('Snefru: options.length ' + this.options.length +
          ' leaves no room in a block (the digest must be at most 480 bits)');
      }
      return super.process();
    }
    if (message.length < size) return;

    const n = hash.length;
    const rounds = roundsOf(options);
    if (rounds < 0 || n > 15 || size !== 4 * (16 - n) || this.processBlock !== ORIGINAL_BLOCK ||
      !wordsOk(hash, 15) || !runtime()) {
      return super.process();
    }

    const base = rt.base;
    const st = base + STATE_OFF;
    const input = base + INPUT_OFF;
    const w = st >> 2;
    for (let k = 0; k < n; k++) i32[w + k] = hash[k];
    u8[st + O_WORDS] = n;
    u8[st + O_ROUNDS] = rounds;
    u8[st + O_BUFFERED] = 0;

    const total = message.length - message.length % size;
    const chunk = rt.cap - rt.cap % size;
    for (let pos = 0; pos < total;) {
      const end = Math.min(pos + chunk, total);
      let bits = 0;
      for (let i = pos, o = input; i < end; i++, o++) {
        const c = message.charCodeAt(i);
        bits |= c;
        u8[o] = c;
      }
      if (bits > 0xff || rt.ex.snefru_blocks(st, input, end - pos) !== 0) {
        // A code unit the wasm code cannot represent: hand over what has been
        // consumed so far (always whole blocks) and let the original do the rest.
        if (pos > 0) {
          store(hash, w, n);
          state.message = message.substr(pos);
        }
        return super.process();
      }
      pos = end;
    }
    wasmCalls++;
    store(hash, w, n);
    state.message = message.substr(total);
  }

  /**
   * Finalize hash and return result
   *
   * @returns {string}
   */
  finalize() {
    const state = this.state;
    if (state === null || typeof state !== 'object') return super.finalize();
    const message = state.message;
    const hash = state.hash;
    const length = state.length;
    const size = this.blockSizeInBytes;
    if (typeof message !== 'string' || typeof length !== 'number' || typeof size !== 'number' ||
      !wordsOk(hash, 14) || size !== 4 * (16 - hash.length) || message.length >= size ||
      this.process !== Snefru.prototype.process || this.processBlock !== ORIGINAL_BLOCK ||
      this.addLengthBits !== ORIGINAL_BITS || this.addPaddingZero !== ORIGINAL_PAD ||
      this.getStateHash !== ORIGINAL_HASH) {
      return super.finalize();
    }
    const rounds = roundsOf(this.options);
    if (rounds < 0 || !runtime()) return super.finalize();

    const n = hash.length;
    const base = rt.base;
    const st = base + STATE_OFF;
    const m = message.length;
    // Fill the scratch State. Nothing in `this` is touched until the message is
    // known to be representable.
    for (let i = 0, o = st + O_BUF; i < m; i++, o++) {
      const c = message.charCodeAt(i);
      if (c > 0xff) return super.finalize();
      u8[o] = c;
    }
    const w = st >> 2;
    for (let k = 0; k < n; k++) i32[w + k] = hash[k];
    u8[st + O_WORDS] = n;
    u8[st + O_ROUNDS] = rounds;
    u8[st + O_BUFFERED] = m;
    // Only ToInt32(length) matters to the original's length field.
    u32[(st + O_LENGTH) >> 2] = length;

    const out = base + OUT_OFF;
    if (rt.ex.snefru_final(st, out) !== 0) return super.finalize();
    wasmCalls++;

    // What the original leaves behind: advanced hash words, drained buffer.
    store(hash, w, n);
    state.message = '';
    return String.fromCharCode.apply(null, u8.subarray(out, out + 4 * n));
  }
}

export default Snefru;
